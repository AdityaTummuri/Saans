let current = 'en';

export function setLanguage(lang) {
  current = lang in STRINGS ? lang : 'en';
}

export function getLanguage() {
  return current;
}

/** Translate a key, filling {placeholders}. Missing keys fall back to English, then the key. */
export function t(key, vars = {}) {
  const raw = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  const all = { pm: 'PM2.5', pmname: 'PM2.5', ...vars };
  return raw.replace(/\{(\w+)\}/g, (m, name) => (name in all ? String(all[name]) : m));
}
